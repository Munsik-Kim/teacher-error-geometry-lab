"""Update/check the current public inventory; never modify historical evidence."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true", help="Check without writing")
args = parser.parse_args()


def digest(data):
    return hashlib.sha256(data).hexdigest()


def canonical(data):
    return json.dumps(data, sort_keys=True, separators=(",", ":")).encode()


def public_file(path):
    relative = path.relative_to(ROOT)
    return path.is_file() and not path.is_symlink() and not any(
        part in (".git", ".venv", ".cache", "__pycache__", "build", "dist") or part.endswith(".egg-info")
        for part in relative.parts) and path.suffix != ".pyc"


def entry(path):
    data = path.read_bytes()
    return {"path": path.relative_to(ROOT).as_posix(), "bytes": len(data), "sha256": digest(data)}


def update(name, value):
    path = ROOT / name
    if args.check:
        if json.loads(path.read_text()) != value:
            raise SystemExit("Manifest mismatch: " + name)
    else:
        path.write_text(json.dumps(value, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


# Historical archive is an immutable input. It is never regenerated by this tool.
evidence = json.loads((ROOT / "evidence/manifest.json").read_text())["archive"]
archive = ROOT / "evidence" / evidence["path"]
if archive.stat().st_size != evidence["bytes"] or digest(archive.read_bytes()) != evidence["sha256"]:
    raise SystemExit("Historical archive bytes/hash mismatch")
source_paths = []
for directory in ("src", "configs", "tests", "tests_p2", "tests_public", "scripts", ".github"):
    source_paths.extend(p for p in (ROOT / directory).rglob("*") if public_file(p))
source_paths.extend(ROOT / name for name in ("pyproject.toml", "requirements.txt", "requirements-lock.txt", "environment.json", "LICENSE", "NOTICE", ".gitignore", ".gitattributes"))
sources = [entry(p) for p in sorted(set(source_paths))]
source = json.loads((ROOT / "publication/source_manifest.json").read_text())
source.update(source_manifest=sources, source_bundle_sha256=digest(canonical(sources)))
update("publication/source_manifest.json", source)
files = [entry(p) for p in sorted(ROOT.rglob("*")) if public_file(p) and p.relative_to(ROOT).as_posix() != "publication/FILES.json"]
inventory = json.loads((ROOT / "publication/FILES.json").read_text())
inventory.update(file_count_excluding_self=len(files), bytes_excluding_self=sum(e["bytes"] for e in files),
                 public_file_bundle_sha256=digest(canonical(files)), active_public_source_bundle_sha256=source["source_bundle_sha256"], files=files)
update("publication/FILES.json", inventory)
print(json.dumps({"status": "PASS", "mode": "check" if args.check else "update", "public_files": len(files) + 1,
                  "source_bundle_sha256": source["source_bundle_sha256"], "public_file_bundle_sha256": inventory["public_file_bundle_sha256"]}))
